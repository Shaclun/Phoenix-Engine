	const listeners = [];
	let current = FALLBACK;
	let loadedFromLocal = false;

	try {
		const stored = localStorage.getItem(STORAGE_KEY);
		if (stored && dictionaries[stored]) {
			current = stored;
			loadedFromLocal = true;
		}
	} catch (e) {}

	try { document.documentElement.setAttribute("lang", current); } catch (e) {}

	if (!loadedFromLocal && global.PhoenixStorage) {
		global.PhoenixStorage.get(STORAGE_KEY, function (value) {
			if (value && dictionaries[value] && value !== current) {
				current = value;
				try { localStorage.setItem(STORAGE_KEY, value); } catch (e) {}
				try { document.documentElement.setAttribute("lang", value); } catch (e) {}
				listeners.forEach(function (fn) { try { fn(current); } catch (e) {} });
				applyDom(document);
			}
		});
	}

	function t(key) {
		const dict = dictionaries[current] || dictionaries[FALLBACK];
		if (dict && key in dict) return dict[key];
		const fb = dictionaries[FALLBACK];
		if (fb && key in fb) return fb[key];
		return key;
	}

	function tItem(instance, suffix, fallback) {
		if (!instance) return fallback || "";
		const key = "item." + String(instance).toUpperCase() + "." + (suffix || "name");
		const dict = dictionaries[current] || dictionaries[FALLBACK];
		if (dict && key in dict) return dict[key];
		const fb = dictionaries[FALLBACK];
		if (fb && key in fb) return fb[key];
		return fallback || "";
	}

	function setLang(lang) {
		if (!dictionaries[lang]) return;
		if (current === lang) {
			try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
			if (global.PhoenixStorage) global.PhoenixStorage.set(STORAGE_KEY, lang);
			try { document.documentElement.setAttribute("lang", lang); } catch (e2) {}
			return;
		}
		current = lang;
		try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
		if (global.PhoenixStorage) global.PhoenixStorage.set(STORAGE_KEY, lang);
		try { document.documentElement.setAttribute("lang", lang); } catch (e2) {}
		listeners.forEach(function (fn) {
			try { fn(lang); } catch (err) {}
		});
		applyDom(document);
	}

	function getLang() { return current; }
	function listLangs() { return Object.keys(dictionaries); }
	function hasLang(lang) { return !!dictionaries[lang]; }

	function onChange(fn) { listeners.push(fn); }

	function applyDom(scope) {
		(scope || document).querySelectorAll("[data-t]").forEach(function (node) {
			const key = node.getAttribute("data-t");
			node.textContent = t(key);
		});
		(scope || document).querySelectorAll("[data-t-placeholder]").forEach(function (node) {
			const key = node.getAttribute("data-t-placeholder");
			node.setAttribute("placeholder", t(key));
		});
		(scope || document).querySelectorAll("[data-t-title]").forEach(function (node) {
			const key = node.getAttribute("data-t-title");
			node.setAttribute("title", t(key));
		});
		(scope || document).querySelectorAll("[data-t-aria-label]").forEach(function (node) {
			const key = node.getAttribute("data-t-aria-label");
			node.setAttribute("aria-label", t(key));
		});
	}

	global.PhoenixI18n = {
		t: t,
		tItem: tItem,
		setLang: setLang,
		getLang: getLang,
		listLangs: listLangs,
		hasLang: hasLang,
		onChange: onChange,
		applyDom: applyDom
	};
