def tr(language: str, key: str, **values: object) -> str:
    """Return a translated string, falling back to English and then the key."""
    table = TRANSLATIONS.get(language, TRANSLATIONS["en"])
    text = table.get(key, TRANSLATIONS["en"].get(key, key))
    try:
        return text.format(**values)
    except (KeyError, ValueError):
        return text
