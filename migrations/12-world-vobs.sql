CREATE TABLE IF NOT EXISTS `phoenix_world_vobs` (
  `id` INT(11) NOT NULL AUTO_INCREMENT,
  `vobId` VARCHAR(96) NOT NULL,
  `name` VARCHAR(128) DEFAULT '',
  `visual` VARCHAR(128) NOT NULL,
  `world` VARCHAR(96) NOT NULL DEFAULT 'NEWWORLD',
  `posX` FLOAT NOT NULL DEFAULT 0,
  `posY` FLOAT NOT NULL DEFAULT 0,
  `posZ` FLOAT NOT NULL DEFAULT 0,
  `rotX` FLOAT NOT NULL DEFAULT 0,
  `rotY` FLOAT NOT NULL DEFAULT 0,
  `rotZ` FLOAT NOT NULL DEFAULT 0,
  `interactive` TINYINT(1) NOT NULL DEFAULT 0,
  `active` TINYINT(1) NOT NULL DEFAULT 1,
  `createdBy` INT(11) NULL,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `vob_unique` (`vobId`),
  KEY `world_idx` (`world`),
  KEY `visual_idx` (`visual`)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;
